import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const iconSet = JSON.parse(readFileSync(require.resolve('@iconify-json/ph/icons.json'), 'utf8'));

const NAMES = [
  'list',
  'text-aa',
  'sun',
  'coffee',
  'moon',
  'caret-right',
  'caret-down',
  'caret-double-left',
  'x',
  'magnifying-glass',
  'clock-counter-clockwise',
  'bookmark-simple',
  'bookmark-simple-fill',
  'check',
  'sidebar-simple',
  'house',
  'chat-circle',
  'copy',
  'arrow-left',
  'arrow-right',
  'arrow-up',
  'folder-simple',
  'book-open',
  'list-bullets',
  'arrows-out-simple',
  'arrows-in-simple',
  'tree-structure',
  'file-text',
];

const entries = NAMES.map((name) => {
  const icon = iconSet.icons[name];
  if (!icon) throw new Error(`Phosphor icon "${name}" not found in @iconify-json/ph`);
  const width = icon.width ?? iconSet.width;
  const height = icon.height ?? iconSet.height;
  return `  ${JSON.stringify(name)}: { body: ${JSON.stringify(icon.body)}, width: ${width}, height: ${height} },`;
});

const output = `// Generated by scripts/generate-icons.mjs from @iconify-json/ph. Do not edit.
export const icons = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof icons;
`;

writeFileSync(new URL('../src/lib/icons.generated.ts', import.meta.url), output);
console.log(`Wrote ${NAMES.length} icons to src/lib/icons.generated.ts`);
